def sqli_macros(con):
    """Scalars the prose quotes. Absent tables mean the stage has not run."""
    if not con.execute("""SELECT COUNT(*) FROM sqlite_master
                          WHERE type='table' AND name='mt_sqli_combo'""").fetchone()[0]:
        return []
    q = lambda sql: con.execute(sql).fetchone()[0]
    def col(c):
        return {a: n for a, n in con.execute(
            f"SELECT arm, SUM({c}) FROM mt_sqli_combo GROUP BY arm")}
    brk, effb = col("n_breakout"), col("n_eff_breakout")
    eff = q("""SELECT COUNT(DISTINCT v.value) FROM mt_sqli_value v
               JOIN mt_sqli_case c USING(value_id) WHERE c.effective=1""")
    vals = [
        ("SqliCases", num(q("SELECT COUNT(*) FROM mt_sqli_case"))),
        ("SqliPayloads", num(q("SELECT COUNT(*) FROM mt_sqli_value"))),
        # The shape of that case count.  Hosts and arms are each typed by hole
        # kind and only compatible pairs run, so the per-payload figure is
        # hosts(value)*arms(value) + hosts(ident)*arms(ident).  Count what
        # appears in mt_sqli_case rather than what mt_sqli_arm declares: the
        # typed ?V and ?I arms are swept separately into mt_sqli_strict.
        ("SqliValueHosts", num(q(
            "SELECT COUNT(DISTINCT host_id) FROM mt_sqli_case "
            "WHERE host_id IN (SELECT host_id FROM mt_sqli_host WHERE hole=1)"))),
        ("SqliIdentHosts", num(q(
            "SELECT COUNT(DISTINCT host_id) FROM mt_sqli_case "
            "WHERE host_id IN (SELECT host_id FROM mt_sqli_host WHERE hole=2)"))),
        ("SqliValueArms", num(q(
            "SELECT COUNT(DISTINCT arm_id) FROM mt_sqli_case "
            "WHERE arm_id IN (SELECT arm_id FROM mt_sqli_arm WHERE hole=1)"))),
        ("SqliIdentArms", num(q(
            "SELECT COUNT(DISTINCT arm_id) FROM mt_sqli_case "
            "WHERE arm_id IN (SELECT arm_id FROM mt_sqli_arm WHERE hole=2)"))),
        ("SqliCasesPerPayload", num(q(
            "SELECT COUNT(*) FROM mt_sqli_case WHERE value_id="
            "(SELECT MIN(value_id) FROM mt_sqli_case)"))),
        ("SqliFamilies", num(q("SELECT COUNT(DISTINCT family) FROM mt_sqli_value"))),
        ("SqliEffective", num(eff)),
        # The only treatment-arm cases that do not compile: payloads carrying a
        # zero byte, which ends a SQLite statement.
        ("SqliIdentMtMalformed", num(q(
            "SELECT COUNT(*) FROM mt_sqli_case c JOIN mt_sqli_arm a USING(arm_id) "
            "WHERE a.name='ident_mt' AND c.verdict='MALFORMED'"))),
        ("SqliNulPayloads", num(q(
            "SELECT COUNT(*) FROM mt_sqli_value WHERE instr(value, char(0))>0"))),
        # the matchertext holes: zero breakouts
        ("SqliMtBreakout", num(brk.get("mt", 0))),
        ("SqliMtStrictBreakout", num(brk.get("mt_strict", 0))),
        ("SqliIdentMtBreakout", num(brk.get("ident_mt", 0))),
        # the controls, over the effective set
        ("SqliConcatBreakout", num(effb.get("concat", 0))),
        ("SqliIdentConcatBreakout", num(effb.get("ident_concat", 0))),
        # legacy value defences also hold
        ("SqliQuoteBreakout", num(brk.get("quote", 0))),
        ("SqliBindBreakout", num(brk.get("bind", 0))),
        ("SqliMtStrictRejected", num(q("""SELECT SUM(n_rejected) FROM mt_sqli_combo
                                          WHERE arm='mt_strict'""") or 0)),
    ]
    if con.execute("""SELECT COUNT(*) FROM sqlite_master
                      WHERE type='table' AND name='mt_sqli_strict'""").fetchone()[0]:
        s = {a: r for a, *r in con.execute(
            """SELECT arm, inert, breakout, rejected, refused
               FROM mt_sqli_strict""")}
        v = s.get("mt_v", [0, 0, 0, 0])
        i = s.get("ident_i", [0, 0, 0, 0])
        # the strict typed API: contains every payload, zero breakouts
        vals += [
            ("SqliStrictValueInert", num(v[0])),
            ("SqliStrictValueRejected", num(v[2])),
            ("SqliStrictValueBreakout", num(v[1])),
            ("SqliStrictIdentInert", num(i[0])),
            ("SqliStrictIdentRejected", num(i[2])),
            ("SqliStrictIdentBreakout", num(i[1])),
            # every text-splicing path is refused, the same count per delivery
            ("SqliStrictRefused", num(s.get("concat", [0, 0, 0, 0])[3])),
        ]
    sab = EXPORTS / "sqli_sabotage.csv"
    if sab.exists():
        with open(sab, newline="") as f:
            rows = list(csv.DictReader(f))
        vals += [("SqliSabotageDetect",
                  pct(max((float(r["detection_rate"]) for r in rows), default=0.0), 1)),
                 ("SqliSabotageBreakouts", num(sum(int(r["to_breakout"]) for r in rows))),
                 ("SqliSabotageProbeBreakouts",
                  num(sum(int(r["to_breakout_probe"]) for r in rows)))]
    benign = EXPORTS / "sqli_benign_rejection.csv"
    if benign.exists():
        with open(benign, newline="") as f:
            r = next(csv.DictReader(f))
        texts, rejected = int(r["texts"]), int(r["rejected"])
        vals += [("SqliBenignTexts", num(texts)),
                 ("SqliBenignRejected", num(rejected)),
                 ("SqliBenignRejectedShare", pct(rejected / max(texts, 1), 2))]
    return vals


