def num(n):
    return f"{n:,}".replace(",", "{,}")


def pct(x, digits=0):
    return f"{x * 100:.{digits}f}\\%"


def macro(name, value):
    return f"\\newcommand{{\\data{name}}}{{{value}\\xspace}}\n"


def containment(con):
    """Per-stratum inert / rejected / outside over payload-backed CVEs, the
    outside split by the premise it fails, and each skeleton group as
    (stratum, CVEs, contained CVEs) for the bootstrap."""
    inert, reject, outside = defaultdict(int), defaultdict(int), defaultdict(int)
    semantic = document = nonmatcher = unknown = 0
    groups = []
    for syn, sk, n in con.execute(f"""SELECT {STRATUM}, g.skeleton, COUNT(*)
                                      FROM syntactic_group g JOIN classification c USING(cve_id)
                                      GROUP BY g.group_id, 1"""):
        ok, mech, _ = matchertext.assess(syn, sk)
        groups.append((syn, n, n if ok else 0))
        if ok:
            (inert if mech == "inert" else reject)[syn] += n
        else:
            outside[syn] += n
            # An outside case fails a premise of the threat model: the sink
            # executes the value (A4), no hole receives it (A2), or the context
            # has no matcher delimiters.
            if syn == "html_document":
                document += n
            elif syn in matchertext.SEMANTIC or syn == "html_dom":
                semantic += n
            elif syn == "unknown":
                unknown += n          # no syntax label, so no premise to name
            else:
                nonmatcher += n
    return inert, reject, outside, (semantic, document, nonmatcher, unknown), groups


def post_stratify(con, inert, reject, outside):
    """Reweight the per-syntax containment rate by the corpus syntax mix.

    Payload-backed CVEs are not a random sample of the corpus. SQL is 1.7x
    over-represented, because a SQL injection payload is a literal string a
    write-up can quote, whereas code-eval and argument payloads are usually
    built at run time and never appear verbatim. Payload availability therefore
    correlates with syntax, and specifically with matcher-hostable syntax: 85%
    of the payload-backed subset is hostable against 80% of the corpus.

    Multiplying the pooled containment rate by the corpus inherits that skew.
    Weighting a rate per syntax by the corpus counts removes it.

    The rates themselves are not measured, except for HTML/DOM: the threat
    model contains every payload of a HOST syntax and none outside, so the
    syntax label fixes the rate, and a syntax with no payload-backed CVE gets
    the same rule. Only a PAYLOAD_DEPENDENT syntax has
    a rate the payloads decide. The estimate is therefore the hostable count
    less the HTML/DOM javascript: sinks.
    """
    est = 0.0
    for syn, n in con.execute(f"SELECT {STRATUM}, COUNT(*) FROM classification c GROUP BY 1"):
        backed = inert[syn] + reject[syn] + outside[syn]
        if backed:
            est += n * (inert[syn] + reject[syn]) / backed
        elif syn in matchertext.HOST:
            est += n
    return est


def tbl_mech(inert, reject, outside):
    hosted = [s for s in DISPLAY if s in matchertext.HOST
              and (inert[s] or reject[s] or outside[s])]
    other = [s for s in DISPLAY if s not in matchertext.HOST and outside[s]]
    lines = ["\\begin{tabular}{lrrr}", "\\toprule",
             "Syntax & Inert embed & Rejected & Outside \\\\", "\\midrule"]
    for s in sorted(hosted, key=lambda s: -(inert[s] + reject[s] + outside[s])):
        lines.append(f"{DISPLAY[s]:<19} & {num(inert[s]):>7} & {num(reject[s]):>3} "
                     f"& {num(outside[s]):>3} \\\\")
    lines.append("\\midrule")
    for s in sorted(other, key=lambda s: -outside[s]):
        lines.append(f"{DISPLAY[s]:<19} & --- & --- & {num(outside[s]):>3} \\\\")
    lines += ["\\midrule",
              f"Total & {num(sum(inert.values()))} & {num(sum(reject.values()))} "
              f"& {num(sum(outside.values()))} \\\\",
              "\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def place(*pairs):
    """Lay out (center_column, text) pairs on one line."""
    line = ""
    for col, text in pairs:
        start = col - len(text) // 2
        line += " " * max(0, start - len(line)) + text
    return line


def connector(*spans):
    """A tree connector line: each span is (left, right, {column: glyph}),
    drawn as a horizontal rule from left to right with the glyphs on it."""
    line = [" "] * (max(right for _, right, _ in spans) + 1)
    for left, right, glyphs in spans:
        line[left:right + 1] = "─" * (right - left + 1)
        for col, glyph in glyphs.items():
            line[col] = glyph
    return "".join(line).rstrip()


def fig_tree(grouped, contained, inert, reject, outside, semantic, document, nonmatcher, unknown):
    """The two-decision containment tree, each question above its branches.

    Emitted as a complete verbatim block rather than macros, because verbatim
    does not expand them; the paper \\input{}s this file inside its figure.
    """
    p = lambda a, b: f"({round(100 * a / b) if b else 0}%)"
    # Column centres of the leaves: two below the context test, three below
    # OUTSIDE, one per premise an outside case fails.
    sink, doc, nm = 46, 64, 86
    return "\n".join([
        r"\begin{verbatim}",
        place((35, f"{grouped:,} payload-backed CVEs")),
        place((35, "matcher-delimitable context?")),
        connector((20, 50, {20: "┌", 35: "┴", 50: "┐"})),
        place((20, "yes"), (50, "no: OUTSIDE")),
        place((20, f"{contained:,} {p(contained, grouped)}: VERIFY(v)?"),
              (50, f"{outside:,} {p(outside, grouped)}")),
        connector((8, 32, {8: "┌", 20: "┴", 32: "┐"}),
                  (sink, nm, {sink: "┌", 50: "┴", doc: "┬", nm: "┐"})),
        place((8, "pass"), (32, "fail"), (sink, f"{semantic:,}"), (doc, f"{document:,}"),
              (nm, f"{nonmatcher:,}")),
        place((8, "INERT EMBED"), (32, "REJECTED"), (sink, "execution sinks"),
              (doc, "whole documents"), (nm, "non-matcher delimiters")),
        place((8, f"{inert:,} {p(inert, contained)}"), (32, f"{reject:,} {p(reject, contained)}"),
              (sink, "templates, eval,"), (doc, "uploaded SVG,"), (nm, "shell ; | &")),
        place((sink, "javascript:"), (doc, "HTML, PDF"), (nm, "CR/LF, XML <>")),
        # Each outside branch is tagged with the threat-model premise it fails
        # (threat.tex); a CVE with no syntax label names none.
        place((sink, "(A4)"), (doc, "(A2)"), (nm, f"+ {unknown:,} of no syntax")),
        r"\end{verbatim}",
    ]) + "\n"


