#!/usr/bin/env python3
"""Emit every corpus figure the PLDI paper quotes as LaTeX macros.

The paper must never carry a hand-copied number. This script reads the
analysis results (result/global/*.md and result/repos/$ORG/@org/**/*.md,
written by run-analysis.py) and writes ../doc/generated/numbers.tex, which
doc/main.tex pulls in.

Scalar macros end in \\xspace so they can be written inline without a
trailing {}. Counts are formatted 13{,}691 and percentages 98.69\\%,
matching the prose style. The table bodies \\dataTblCategoryRows and
\\dataTblHostRows expand to complete tabular rows.

Usage: python3 latex.py   (from any directory)
"""
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
RESULT = os.path.join(HERE, "result")
REPOS = os.path.join(RESULT, "repos")
GLOBAL = os.path.join(RESULT, "global")
OUT = os.path.join(HERE, "..", "doc", "generated", "numbers.tex")

HEADER = ("%% GENERATED by LLVM/latex.py -- do not edit.\n"
          "%% Regenerate with: python3 LLVM/latex.py (reads LLVM/result/)\n")

# Host languages of tab:eval:hostlang, besides the least-compliant host,
# which the table always adds.
TABLE_HOSTS = ["JavaScript", "Java", "Python", "Go", "C++", "TypeScript", "C", "C#", "Rust"]

# Categories of tab:eval:categories have at least this share of classified samples.
CATEGORY_MIN_SHARE = 1.0


# ---------- formatting ----------
def num(n):
    return f"{round(n):,}".replace(",", "{,}")


def pct(x, digits=2):
    return f"{x:.{digits}f}\\%"


def millions(n, digits=1, unit="~million"):
    return f"{n / 1e6:.{digits}f}{unit}"


def short(n, digits=1):
    """Table form: 187.8\\,M, or 432\\,k below a million."""
    return f"{n / 1e6:.{digits}f}\\,M" if n >= 1e6 else f"{n / 1e3:.0f}\\,k"


def tex_name(lang):
    return lang.replace("#", "\\#")


def macro_name(lang):
    special = {"C++": "Cpp", "C#": "CSharp"}
    return special.get(lang, "".join(c for c in lang if c.isalnum()))


def macro(name, value):
    return f"\\newcommand{{\\data{name}}}{{{value}\\xspace}}\n"


# ---------- reading the analysis tables ----------
def table(path, after="## Data"):
    """Rows of the first markdown table (after the `after` heading, if given)."""
    lines = open(path).read().splitlines()
    i = 0
    if after:
        while i < len(lines) and lines[i].strip() != after:
            i += 1
    rows, header = {}, None
    for line in lines[i:]:
        if not line.startswith("|"):
            if header:
                break
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = cells
        elif not set(cells[0]) <= set("-"):
            rows[cells[0]] = cells[1:]
    return rows


def metrics(path):
    """Metric -> [Strings, Documentation, Documentation Relaxed] (or [File Stats])."""
    return {k: [float(x) for x in v] for k, v in table(path).items()}


def categories(path):
    """Category -> count, violations, toothpicks."""
    return {k: dict(count=float(v[0]), viol=float(v[2]), tp=float(v[3]))
            for k, v in table(path, after=None).items()}


def main():
    orgs = sorted(o for o in os.listdir(REPOS)
                  if os.path.isfile(os.path.join(REPOS, o, "@org", "strings.md")))
    repos = sum(1 for o in orgs for d in os.listdir(os.path.join(REPOS, o))
                if d != "@org" and os.path.isdir(os.path.join(REPOS, o, d)))

    g = metrics(os.path.join(GLOBAL, "strings.md"))
    f = metrics(os.path.join(GLOBAL, "files.md"))
    cats = categories(os.path.join(GLOBAL, "language_stats.md"))

    str_n, doc_n = g["Sample Size"][0], g["Sample Size"][1]
    toothpicks = g["Total Toothpicks"][0]
    # Reduction and compliance cover only in-scope samples: all but BinaryData and
    # PseudoBinaryData string literals. Results from before the split have no such rows.
    scope_toothpicks = g.get("In-Scope Toothpicks", g["Total Toothpicks"])[0]
    converted = g["Total Toothpicks (Converted)"][0]
    violations = g["Non-Compliance Count"][0]
    reduction = g["Toothpick Reduction Total (%)"][0]

    classified = sum(c["count"] for c in cats.values())
    share = {k: 100 * c["count"] / classified for k, c in cats.items()}

    # per organisation and per host language
    org_reduction = []
    hosts = {}
    for o in orgs:
        org_reduction.append(metrics(os.path.join(REPOS, o, "@org", "strings.md"))
                             ["Toothpick Reduction Total (%)"][0])
        base = os.path.join(REPOS, o, "@org", "language_stats")
        if not os.path.isdir(base):
            continue
        for lang in os.listdir(base):
            p = os.path.join(base, lang, "strings.md")
            if not os.path.isfile(p):
                continue
            s = metrics(p)
            h = hosts.setdefault(lang, dict(orgs=0, n=0, scope_n=0, compliant=0, tp=0,
                                            scope_tp=0, tpc=0,
                                            maxdepth=0, maxdepth_valid=0, cats={}))
            h["orgs"] += 1
            h["n"] += s["Sample Size"][0]
            h["scope_n"] += s.get("In-Scope Samples", s["Sample Size"])[0]
            h["compliant"] += s["Compliant Samples"][0]
            h["tp"] += s["Total Toothpicks"][0]
            h["scope_tp"] += s.get("In-Scope Toothpicks", s["Total Toothpicks"])[0]
            h["tpc"] += s["Total Toothpicks (Converted)"][0]
            depth = s["Highest Per-Sample Raw Max Depth"][0]
            if depth > h["maxdepth"]:
                # The valid depth of this org's deepest sample is at most the
                # org's highest valid depth for the language.
                h["maxdepth"] = depth
                h["maxdepth_valid"] = s["Highest Per-Sample Valid Max Depth"][0]
            cp = os.path.join(base, lang, "language_stats.md")
            if os.path.isfile(cp):
                for k, v in categories(cp).items():
                    c = h["cats"].setdefault(k, dict(count=0, viol=0, tp=0))
                    for field in c:
                        c[field] += v[field]
    for h in hosts.values():
        h["compliance"] = 100 * h["compliant"] / h["scope_n"] if h["scope_n"] else 100.0
        h["reduction"] = 100 * (h["scope_tp"] - h["tpc"]) / h["scope_tp"] if h["scope_tp"] else 0.0

    def cat_rate(lang, cat):
        c = hosts[lang]["cats"][cat]
        return c["viol"] / c["count"]

    def cat_violation_share(lang, cat):
        cs = hosts[lang]["cats"]
        return 100 * cs[cat]["viol"] / sum(c["viol"] for c in cs.values())

    def cat_toothpick_share(lang, cat):
        return 100 * hosts[lang]["cats"][cat]["tp"] / hosts[lang]["tp"]

    least_compliant = min(hosts, key=lambda h: hosts[h]["compliance"])
    deepest = max(hosts, key=lambda h: hosts[h]["maxdepth"])
    q1, _, q3 = statistics.quantiles(org_reduction, n=4)
    prose = [hosts[h]["cats"]["PlainText"] for h in ("C++", "Java")]

    vals = [
        # corpus
        ("Orgs", num(len(orgs))),
        ("Repos", num(repos)),
        ("Files", millions(f["Sample Size"][0], 2)),
        ("FilesShort", short(f["Sample Size"][0], 2)),
        ("StrSamples", millions(str_n)),
        ("StrSamplesShort", short(str_n)),
        ("StrSamplesRound", f"{str_n / 1e6:.0f}~million"),
        ("DocSamples", millions(doc_n)),
        ("DocSamplesShort", short(doc_n)),
        ("JsStrSamples", f"{hosts['JavaScript']['n'] / 1e6:.0f}~million"),
        # Q1: compliance
        ("StrCompliance", pct(g["Compliance Rate"][0])),
        ("StrComplianceFloor", pct(int(g["Compliance Rate"][0]), 0)),
        ("DocCompliance", pct(g["Compliance Rate"][1])),
        ("DocComplianceFloor", pct(int(g["Compliance Rate"][1]), 0)),
        ("DocComplianceRelaxed", pct(g["Compliance Rate"][2])),
        ("FileCompliance", pct(f["Compliance Rate"][0])),
        ("FileComplianceRelaxed", pct(f["Compliance Rate Relaxed"][0])),
        ("HostComplianceMin", pct(hosts[least_compliant]["compliance"])),
        ("HostComplianceMax", pct(max(h["compliance"] for h in hosts.values()))),
        ("HostLeastCompliant", tex_name(least_compliant)),
        # Q2: categories
        ("Classified", short(classified)),
        ("ClassifiedShare", pct(100 * classified / str_n, 0)),
        ("Unclassified", short(str_n - classified)),
        ("UnclassifiedViolations", short(violations - sum(c["viol"] for c in cats.values()), 2)),
        ("UnclassifiedToothpicks", short(toothpicks - sum(c["tp"] for c in cats.values()))),
        ("StrViolations", short(violations, 2)),
        ("ToothpicksShort", short(toothpicks)),
        ("RegexViolations", num(cats["Regex"]["viol"])),
        ("RegexShare", pct(share["Regex"], 1)),
        ("ShellViolations", num(cats["Shell"]["viol"])),
        ("ShellShare", pct(share["Shell"], 1)),
        ("CssViolations", num(cats["CSS"]["viol"])),
        ("CssSamples", num(cats["CSS"]["count"])),
        ("BulkShare", pct(share["PlainText"] + share["IdentifierLike"] + share["FilePath"], 0)),
        ("SqlShare", pct(share["SQL"])),
        ("JsonShare", pct(share["JSON"])),
        ("CssShare", pct(share["CSS"])),
        ("XmlShare", pct(share["XML"])),
        ("JsRegexRate", f"{cat_rate('JavaScript', 'Regex'):.2f}"),
        ("JsShellRate", f"{cat_rate('JavaScript', 'Shell'):.2f}"),
        ("JsCssRate", f"{cat_rate('JavaScript', 'CSS'):.2f}"),
        ("CppProseViolationShare", pct(cat_violation_share("C++", "PlainText"), 1)),
        ("JavaProseViolationShare", pct(cat_violation_share("Java", "PlainText"), 1)),
        ("ProseRate", f"{sum(c['viol'] for c in prose) / sum(c['count'] for c in prose):.2f}"),
        # Q3: reduction
        ("Reduction", pct(reduction)),
        ("ReductionRound", pct(reduction, 0)),
        ("Toothpicks", millions(toothpicks)),
        ("ScopeToothpicks", millions(scope_toothpicks)),
        ("ToothpicksConverted", millions(converted)),
        ("BinaryToothpicks", millions(cats["BinaryData"]["tp"] + cats["PseudoBinaryData"]["tp"])),
        ("OrgReductionMin", pct(min(org_reduction))),
        ("OrgReductionMax", pct(max(org_reduction))),
        ("OrgReductionQOne", pct(q1, 0)),
        ("OrgReductionQThree", pct(q3, 0)),
        ("TsRegexToothpickShare", pct(cat_toothpick_share("TypeScript", "Regex"), 1)),
        # Q3: compliant literals the host's existing raw form already holds, and
        # those only a matchertext literal holds
        ("RawHoldable", millions(g["Raw-Form Holdable"][0])),
        ("RawHoldableShare", pct(100 * g["Raw-Form Holdable"][0] / g["Compliant Samples"][0], 1)),
        ("MtOnly", millions(g["Matchertext-Only"][0])),
        ("MtOnlyShare", pct(100 * g["Matchertext-Only"][0] / g["Compliant Samples"][0], 1)),
        # Q4: nesting
        ("StrAvgDepth", f"{g['Avg Per-Sample Raw Max Depth'][0]:.3f}"),
        ("DocAvgDepth", f"{g['Avg Per-Sample Raw Max Depth'][1]:.3f}"),
        ("StrMaxDepth", num(g["Highest Per-Sample Raw Max Depth"][0])),
        ("StrMaxDepthHost", tex_name(deepest)),
        ("StrMaxDepthValidBound", num(hosts[deepest]["maxdepth_valid"])),
    ]
    # every host language: \dataHost<Lang>{Orgs,Samples,Compliance,Reduction,MaxDepth}
    for lang in sorted(hosts):
        h, m = hosts[lang], "Host" + macro_name(lang)
        vals += [(m + "Orgs", num(h["orgs"])), (m + "Samples", short(h["n"])),
                 (m + "Compliance", pct(h["compliance"])), (m + "Reduction", pct(h["reduction"])),
                 (m + "MaxDepth", num(h["maxdepth"]))]

    category_rows = "".join(
        f"{k}\t& {pct(share[k], 1)}\t& {num(c['viol'])}\t& {num(c['tp'])}\t\\\\\n"
        for k, c in sorted(cats.items(), key=lambda kv: -kv[1]["count"])
        if share[k] >= CATEGORY_MIN_SHARE)
    table_hosts = sorted(set(TABLE_HOSTS) | {least_compliant}, key=lambda h: -hosts[h]["n"])
    host_rows = "".join(
        f"{tex_name(lang)}\t& {h['orgs']}\t& {short(h['n'])}\t& {pct(h['compliance'])}"
        f"\t& {pct(h['reduction'])}\t& {num(h['maxdepth'])}\t\\\\\n"
        for lang in table_hosts for h in [hosts[lang]])

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as out:
        out.write(HEADER)
        out.write("".join(macro(k, v) for k, v in vals))
        out.write("%% Rows of tab:eval:categories\n")
        out.write(f"\\newcommand{{\\dataTblCategoryRows}}{{%\n{category_rows}}}\n")
        out.write("%% Rows of tab:eval:hostlang\n")
        out.write(f"\\newcommand{{\\dataTblHostRows}}{{%\n{host_rows}}}\n")
    print(f"wrote {len(vals)} macros and 2 table bodies to {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
